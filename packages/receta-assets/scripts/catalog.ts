// Writes what an agent reads to find an asset without opening every file: catalog.json for
// tools, CATALOG.md for reading and grepping, and src/<category>/index.ts so a category
// imports as one module. All three come from the asset files, so never edit them by hand.
// Run `bun scripts/catalog.ts` after adding or changing an asset. Start at writeCatalog.
import { writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { mapAsyncOrThrow } from '@ontologyio/receta/async'
import * as R from 'remeda'
import { type Asset, CATEGORIES, type Category, ROOT, SRC, readAssets } from './assets'

const PACKAGE = '@ontologyio/receta-assets'

const ABOUT: Record<Category, string> = {
  async: 'Retries, time limits, batching, polling and fallbacks around async work',
  cache: 'Memoized loaders and caches with expiry, size limits and invalidation',
  collection: 'List work: dedupe, top-N, group totals, diffs, upserts, trees and pages',
  control: 'Branching and dispatch: classify a value, route it, guard it',
  filter: 'Ready predicates and predicate builders for search, ranges and facets',
  number: 'Money, percentages, sizes, rounding and small statistics',
  object: 'Payload shaping: redact, rename, defaults, flatten, strip and pick',
  parse: 'Untrusted text and unknown values into typed values or a reason they are not',
  result: 'Result and Option plumbing: combine, recover, convert, collect',
  sort: 'Comparators for multi-key, priority, natural and nullable orders',
  state: 'Immutable updates deep inside state through lenses',
  text: 'Slugs, excerpts, masks, names, case and search highlighting',
  validate: 'Field, form and payload validation that reports every error at once',
}

type Entry = {
  readonly name: string
  readonly category: string
  readonly import: string
  readonly path: string
  readonly summary: string
  readonly useWhen: string
  readonly tags: readonly string[]
  readonly composes: readonly string[]
  readonly signatures: readonly string[]
  readonly hasDiagram: boolean
}

const toEntry = (asset: Asset): Entry => ({
  name: asset.name,
  category: asset.category,
  import: `import { ${asset.name} } from '${PACKAGE}/${asset.category}'`,
  path: asset.path,
  summary: asset.doc.summary,
  useWhen: asset.doc.useWhen,
  tags: asset.doc.tags,
  composes: asset.composes,
  signatures: asset.signatures,
  hasDiagram: asset.doc.flow !== '',
})

const escapeCell = (text: string): string => text.replaceAll('|', '\\|')

const categorySection = ([category, entries]: readonly [string, readonly Entry[]]): string =>
  R.join(
    [
      `## ${category}`,
      '',
      `${ABOUT[category as Category] ?? ''}. Import from \`${PACKAGE}/${category}\`.`,
      '',
      '| Asset | What it does | Built from |',
      '| --- | --- | --- |',
      ...R.map(
        entries,
        (entry) =>
          `| [\`${entry.name}\`](${entry.path})${entry.hasDiagram ? ' ◇' : ''} | ${escapeCell(entry.summary)} | ${escapeCell(R.join(entry.composes, ', '))} |`,
      ),
      '',
    ],
    '\n',
  )

const markdown = (entries: readonly Entry[]): string => {
  const byCategory = R.pipe(
    entries,
    R.groupBy(R.prop('category')),
    R.entries(),
    R.sortBy(([category]) => category),
  )
  const counts = R.join(R.map(byCategory, ([category, members]) => `[${category}](#${category}) ${members.length}`), ' · ')
  return R.join(
    [
      '# Catalog',
      '',
      `<!-- Generated by scripts/catalog.ts from the asset files. Don't edit by hand. -->`,
      '',
      `${entries.length} assets. ${counts}`,
      '',
      'Each asset is one function in one file. Its comment holds the usage, a "Use when" line and',
      'checked examples. ◇ marks an asset whose comment has a diagram of how it works.',
      'Search by name, word or Receta function: `grep -i "retry" CATALOG.md`.',
      '',
      ...R.map(byCategory, categorySection),
    ],
    '\n',
  )
}

const barrel = (assets: readonly Asset[]): string =>
  R.join(
    [
      `// Generated by scripts/catalog.ts. Don't edit by hand.`,
      ...R.map(assets, ({ name }) => `export * from './${name}'`),
      '',
    ],
    '\n',
  )

const writeBarrels = async (assets: readonly Asset[]): Promise<void> => {
  const byCategory = R.groupBy(assets, R.prop('category'))
  await mapAsyncOrThrow(
    R.filter([...CATEGORIES], (category) => byCategory[category] !== undefined),
    (category) => writeFile(join(SRC, category, 'index.ts'), barrel(byCategory[category] ?? [])),
  )
}

const writeCatalog = async (): Promise<void> => {
  const assets = await readAssets()
  const broken = R.filter(assets, ({ problems }) => problems.length > 0)
  if (broken.length > 0) {
    console.error(`Fix these first, \`bun scripts/check.ts\` says why: ${R.join(R.map(broken, R.prop('path')), ', ')}`)
    process.exit(1)
  }
  const unknown = R.filter(assets, ({ category }) => !(CATEGORIES as readonly string[]).includes(category))
  if (unknown.length > 0) {
    console.error(`Unknown categories, add them to CATEGORIES in scripts/assets.ts: ${R.join(R.map(unknown, R.prop('path')), ', ')}`)
    process.exit(1)
  }
  const entries = R.map(assets, toEntry)
  await writeFile(join(ROOT, 'catalog.json'), `${JSON.stringify({ package: PACKAGE, count: entries.length, assets: entries }, null, 2)}\n`)
  await writeFile(join(ROOT, 'CATALOG.md'), markdown(entries))
  await writeBarrels(assets)
  console.log(`Catalog: ${entries.length} assets in ${R.unique(R.map(entries, R.prop('category'))).length} categories`)
}

await writeCatalog()
